test('pnpm-lock v9: packages altindaki anahtarlari okur', () => {
  const text = `
lockfileVersion: '9.0'

packages:

  express@4.21.2:
    resolution: {integrity: sha512-abc}

  lodash@4.17.21:
    resolution: {integrity: sha512-def}

  '@types/node@20.0.0':
    resolution: {integrity: sha512-xyz}

snapshots:

  express@4.21.2: {}
`;
  const deps = parsePnpmLock(text);
  const names = deps.map((d) => d.name);
  assert.ok(names.includes('express'));
  assert.ok(names.includes('lodash'));
  assert.ok(names.includes('@types/node'));
  assert.equal(deps.filter((d) => d.name === 'express').length, 1, 'snapshots tekrarini saymaz');
  assert.equal(deps.find((d) => d.name === 'express').version, '4.21.2');
});

test('pnpm-lock: peer notasyonunu ayristirir', () => {
  const text = `
packages:

  foo@1.2.3(bar@2.0.0):
    resolution: {integrity: sha512-abc}
`;
  const deps = parsePnpmLock(text);
  assert.equal(deps.length, 1);
  assert.equal(deps[0].name, 'foo');
  assert.equal(deps[0].version, '1.2.3');
});

