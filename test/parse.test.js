test('Cargo.toml: dependencies bolumu', () => {
  const text = `
[package]
name = "ornek"
version = "0.1.0"

[dependencies]
serde = "1.0"
tokio = { version = "1", features = ["full"] }
rand = { workspace = true }

[dev-dependencies]
criterion = "0.5"
`;
  const deps = parseCargoToml(text);
  const names = deps.map((d) => d.name);
  assert.ok(names.includes('serde'));
  assert.ok(names.includes('tokio'));
  assert.ok(names.includes('criterion'), 'dev-dependencies de toplanir');
  assert.ok(!names.includes('name'), 'package bolumu karistirilmaz');
  const tokio = deps.find((d) => d.name === 'tokio');
  assert.equal(tokio.range, '1');
});

test('Cargo.toml: BOM uzerinde de calisir', () => {
  const deps = parseCargoToml('\uFEFF[dependencies]\nserde = "1.0"\n');
  assert.equal(deps.length, 1);
  assert.equal(deps[0].name, 'serde');
});

test('Cargo.lock: paket listesi ve kaynakli local paketler', () => {
  const text = `
version = 3

[[package]]
name = "serde"
version = "1.0.203"

[[package]]
name = "ornek"
version = "0.1.0"
dependencies = ["serde"]

[[package]]
name = "local"
version = "0.1.0"
source = "path+file:///../local"
`;
  const deps = parseCargoLock(text);
  const names = deps.map((d) => d.name);
  assert.ok(names.includes('serde'));
  assert.ok(!names.includes('local'), 'path kaynakli paket atlanmali');
  assert.equal(deps.find((d) => d.name === 'serde').version, '1.0.203');
});

test('toml-lite: yorum, diziler ve ic tablolar', () => {
  const doc = parseToml(`
# yorum
top = "deger"  # satir ici yorum
sayi = 42
dizi = ["a", "b", "c"]
inline = { x = 1, y = "iki" }

[bolum]
alt = "deger"

[[liste]]
ad = "bir"

[[liste]]
ad = "iki"
`);
  assert.equal(doc.top, 'deger');
  assert.equal(doc.sayi, 42);
  assert.deepEqual(doc.dizi, ['a', 'b', 'c']);
  assert.equal(doc.inline.x, 1);
  assert.equal(doc.bolum.alt, 'deger');
  assert.equal(doc.liste.length, 2);
  assert.equal(doc.liste[1].ad, 'iki');
});
