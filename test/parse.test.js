// ---------------------------------------------------------------------------
// package.json
// ---------------------------------------------------------------------------

test('package.json: dort bolumu de okur', () => {
  const deps = parsePackageJson(
    JSON.stringify({
      dependencies: { a: '^1.0.0' },
      devDependencies: { b: '^2.0.0' },
      optionalDependencies: { c: '^3.0.0' },
      peerDependencies: { d: '^4.0.0' },
    })
  );
  const byName = Object.fromEntries(deps.map((d) => [d.name, d.section]));
  assert.deepEqual(byName, { a: 'prod', b: 'dev', c: 'optional', d: 'peer' });
});

test('package.json: UTF-8 BOM uzerinde de calisir', () => {
  const text = '\uFEFF' + JSON.stringify({ dependencies: { express: '^4.0.0' } });
  const deps = parsePackageJson(text);
  assert.equal(deps.length, 1);
  assert.equal(deps[0].name, 'express');
});

test('package.json: bozuk JSON bos liste dondurur (cokmemesi)', () => {
  assert.deepEqual(parsePackageJson('{not json'), []);
  assert.deepEqual(parsePackageJson(''), []);
  assert.deepEqual(parsePackageJson(null), []);
});

test('package.json: yerel bagimliliklari atlar', () => {
  const deps = parsePackageJson(
    JSON.stringify({
      dependencies: { local: 'file:../local', link: 'link:../x', normal: '^1.0.0' },
    })
  );
  assert.deepEqual(deps.map((d) => d.name), ['normal']);
});

