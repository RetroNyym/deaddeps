test('yarn.lock v1: klasik bicim', () => {
  const text = `
# THIS IS AN AUTOGENERATED FILE
"@babel/code-frame@^7.0.0":
  version "7.24.0"
  resolved "https://registry.yarnpkg.com/..."

chalk@^4.1.0, chalk@^4.1.2:
  version "4.1.2"
  resolved "https://registry.yarnpkg.com/..."

debug@npm:debug@^4.3.0:
  version "4.3.4"
`;
  const deps = parseYarnLock(text);
  const names = deps.map((d) => d.name);
  assert.ok(names.includes('@babel/code-frame'));
  assert.ok(names.includes('chalk'));
  assert.ok(names.includes('debug'));
  assert.equal(deps.find((d) => d.name === 'chalk').version, '4.1.2');
  assert.equal(deps.filter((d) => d.name === 'chalk').length, 1, 'ayni paket birden fazla anahtarda tektir');
});

test('yarn.lock: boss ve anlasilmaz metin patlamaz', () => {
  assert.deepEqual(parseYarnLock(''), []);
  assert.deepEqual(parseYarnLock('sadece bir satir'), []);
});

