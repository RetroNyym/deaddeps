import test from 'node:test';
import assert from 'node:assert/strict';
import { parsePackageJson, parsePackageLock, parseYarnLock, parsePnpmLock } from '../src/parse/npm.js';
import { parseRequirements, parsePyproject, normalizeName, nameFromRequirement } from '../src/parse/pypi.js';
import { parseCargoToml, parseCargoLock } from '../src/parse/cargo.js';
