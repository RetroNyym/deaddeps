test('package-lock v3: packages alanindan okur', () => {
  const lock = {
    lockfileVersion: 3,
    packages: {
      '': { name: 'root', dependencies: { express: '^4.0.0' } },
      'node_modules/express': { version: '4.21.2' },
      'node_modules/lodash': { version: '4.17.21' },
      'node_modules/@types/node': { version: '20.0.0' },
      'node_modules/.pnpm/whatever': { version: '1.0.0' },
      'node_modules/local-pkg': { version: '1.0.0', resolved: 'file:../local' },
    },
  };
  const deps = parsePackageLock(JSON.stringify(lock));
  const names = deps.map((d) => d.name);
  assert.ok(names.includes('express'));
  assert.ok(names.includes('lodash'));
  assert.ok(names.includes('@types/node'));
  assert.ok(!names.includes('local-pkg'), 'yerel paket atlanmali');
  const express = deps.find((d) => d.name === 'express');
  assert.equal(express.version, '4.21.2');
});

test('package-lock v3: kok paket (bos anahtar) sayilmaz', () => {
  const lock = { packages: { '': { name: 'root', version: '1.0.0' } } };
  assert.deepEqual(parsePackageLock(JSON.stringify(lock)), []);
});

test('package-lock v1: ic ice dependencies yurur', () => {
  const lock = {
    lockfileVersion: 1,
    dependencies: {
      express: {
        version: '4.21.2',
        dependencies: { debug: { version: '4.4.0' } },
      },
      lodash: { version: '4.17.21' },
    },
  };
  const deps = parsePackageLock(JSON.stringify(lock));
  const names = deps.map((d) => d.name).sort();
  assert.deepEqual(names, ['debug', 'express', 'lodash']);
});

test('package-lock: BOM ve bozuk dosya', () => {
  assert.deepEqual(parsePackageLock('\uFEFF' + JSON.stringify({ packages: { 'node_modules/a': { version: '1.0.0' } } })), [
    { name: 'a', version: '1.0.0', dev: false, optional: false },
  ]);
  assert.deepEqual(parsePackageLock('{bozuk'), []);
});

